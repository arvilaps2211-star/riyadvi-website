export type DashboardStats = {
  totalLeads: number;
  contactLeads: number;
  consultations: number;
  healthCheckups: number;
  leadMagnets: number;
  applications: number;
  newLeads: number;
  contacted: number;
  inProgress: number;
  completed: number;
  archived: number;
};

export async function getDashboardStats(): Promise<DashboardStats> {
  const [
    contactCount,
    consultationCount,
    healthCheckupCount,
    leadMagnetCount,
    applicationCount,
    statusCounts,
  ] = await Promise.all([
    pool.query<{ count: string }>("SELECT COUNT(*)::text AS count FROM contact_leads"),
    pool.query<{ count: string }>(
      "SELECT COUNT(*)::text AS count FROM consultation_requests",
    ),
    pool.query<{ count: string }>("SELECT COUNT(*)::text AS count FROM health_checkups"),
    pool.query<{ count: string }>(
      "SELECT COUNT(*)::text AS count FROM lead_magnet_leads",
    ),
    pool.query<{ count: string }>("SELECT COUNT(*)::text AS count FROM applications"),
    // Status breakdown spans every lead-generation table AND applications,
    // since both surface a status the admin needs an at-a-glance count of.
    pool.query<{ status: string; count: string }>(
      `SELECT status, COUNT(*)::text AS count FROM (
         SELECT status FROM contact_leads
         UNION ALL SELECT status FROM consultation_requests
         UNION ALL SELECT status FROM health_checkups
         UNION ALL SELECT status FROM lead_magnet_leads
         UNION ALL SELECT status FROM applications
       ) t
       GROUP BY status`,
    ),
  ]);

  const contactLeads = Number(contactCount.rows[0]?.count ?? "0");
  const consultations = Number(consultationCount.rows[0]?.count ?? "0");
  const healthCheckups = Number(healthCheckupCount.rows[0]?.count ?? "0");
  const leadMagnets = Number(leadMagnetCount.rows[0]?.count ?? "0");
  const applications = Number(applicationCount.rows[0]?.count ?? "0");

  const byStatus: Record<string, number> = {};
  for (const row of statusCounts.rows) {
    byStatus[row.status] = Number(row.count);
  }

  return {
    totalLeads: contactLeads + consultations + healthCheckups + leadMagnets,
    contactLeads,
    consultations,
    healthCheckups,
    leadMagnets,
    applications,
    newLeads: byStatus["new"] ?? 0,
    contacted: byStatus["contacted"] ?? 0,
    inProgress: byStatus["in_progress"] ?? 0,
    completed: byStatus["completed"] ?? 0,
    archived: byStatus["archived"] ?? 0,
  };
}
